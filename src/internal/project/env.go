const envFileRelPath = "config/discourse.env"

type envVar struct {
	Key   string
	Value string
}

// WriteEnvFile renders the workspace's Discourse environment file from the
// current service configuration and returns the generated values. The file
// contains database credentials, so it is written with owner-only access.
func (m *Manager) WriteEnvFile(ctx context.Context, ws *workspace.Workspace) ([]envVar, error) {
	connection, err := m.services.WorkspaceConnection(ws)
	if err != nil {
		return nil, err
	}
	appExecution := runtime.ExecutionNative
	if ruby, findErr := m.runtime.FindBinary(ctx, "ruby"); findErr == nil {
		appExecution = ruby.Execution
	}
	pgHost := connection.PostgresHost
	redisHost := connection.RedisHost
	if appExecution != runtime.ExecutionNative {
		pgHost = m.crossExecutionHost(ctx, appExecution, "pg_ctl", pgHost)
		redisHost = m.crossExecutionHost(ctx, appExecution, "redis-server", redisHost)
	}

	values := []envVar{
		{"RAILS_ENV", "development"},
		{"DISCOURSE_ENV", "development"},
		{"DISCOURSE_HOSTNAME", "localhost"},
		{"DISCOURSE_DB_HOST", pgHost},
		{"DISCOURSE_DB_PORT", strconv.Itoa(connection.PostgresPort)},
		{"DISCOURSE_DB_NAME", connection.PostgresDatabase},
		{"DISCOURSE_DB_USERNAME", connection.PostgresUsername},
		{"DISCOURSE_DB_PASSWORD", connection.PostgresPassword},
	}
	if connection.PostgresTLS {
		values = append(values, envVar{"DISCOURSE_DB_SSL", "true"})
	}
	values = append(values,
		envVar{"DISCOURSE_REDIS_HOST", redisHost},
		envVar{"DISCOURSE_REDIS_PORT", strconv.Itoa(connection.RedisPort)},
		envVar{"DISCOURSE_REDIS_DB", strconv.Itoa(connection.RedisDatabase)},
	)
	if connection.RedisUsername != "" {
		values = append(values, envVar{"DISCOURSE_REDIS_USERNAME", connection.RedisUsername})
	}
	if connection.RedisPassword != "" {
		values = append(values, envVar{"DISCOURSE_REDIS_PASSWORD", connection.RedisPassword})
	}
	if connection.RedisTLS {
		values = append(values, envVar{"DISCOURSE_REDIS_USE_SSL", "true"})
	}

	var builder strings.Builder
	builder.WriteString("# Generated by hxxDiscourseDevKit. Do not commit or share.\n")
	builder.WriteString("# 该文件包含本地开发数据库凭据，已限制为当前用户可读写。\n")
	builder.WriteString("# Generated at " + time.Now().UTC().Format(time.RFC3339) + "\n\n")
	for _, item := range values {
		builder.WriteString(item.Key)
		builder.WriteString("=")
		builder.WriteString(strconv.Quote(item.Value))
		builder.WriteString("\n")
	}
	path := m.envFilePath(ws)
	if err := store.WriteFileAtomicProtected(path, []byte(builder.String()), 0o600, secret.ProtectFile); err != nil {
		return nil, fmt.Errorf("写入 Discourse 环境文件: %w", err)
	}
	m.log.Info("discourse environment written", "workspace_id", ws.WorkspaceID, "path", path)
	return values, nil
}

func (m *Manager) envFilePath(ws *workspace.Workspace) string {
	return filepath.Join(m.paths.WorkspaceDir(ws.WorkspaceID), envFileRelPath)
}

// processEnvironment returns the workspace environment entries as KEY=value
// pairs. The runtime merges them with the daemon environment and handles WSL
// forwarding, so only the Discourse-specific values belong here.
func (m *Manager) processEnvironment(ws *workspace.Workspace, extra ...envVar) ([]string, error) {
	values := []envVar{}
	path := m.envFilePath(ws)
	data, err := os.ReadFile(path)
	if err == nil {
		parsed, parseErr := parseEnvFile(string(data))
		if parseErr != nil {
			return nil, fmt.Errorf("解析 %s: %w", path, parseErr)
		}
		values = append(values, parsed...)
	} else if !os.IsNotExist(err) {
		return nil, err
	}
	values = append(values, extra...)
	result := make([]string, 0, len(values))
	for _, item := range values {
		result = append(result, item.Key+"="+item.Value)
	}
	return result, nil
}

// crossExecutionHost returns a reachable host for a managed service when the
// application runs in WSL and the service runs natively on Windows.
func (m *Manager) crossExecutionHost(ctx context.Context, appExecution, tool, host string) string {
	if !isLoopbackHost(host) {
		return host
	}
	cfg := m.cfg.Get()
	mode := "managed"
	switch tool {
	case "pg_ctl":
		mode = cfg.Services.PostgreSQL.Mode
	case "redis-server":
		mode = cfg.Services.Redis.Mode
	}
	if mode != "managed" {
		return host
	}
	found, err := m.runtime.FindBinary(ctx, tool)
	if err != nil || found.Execution != runtime.ExecutionNative {
		return host
	}
	gateway := m.wslGatewayHost(ctx, appExecution)
	if gateway == "" {
		return host
	}
	return gateway
}

func (m *Manager) wslGatewayHost(ctx context.Context, execution string) string {
	if !strings.HasPrefix(execution, "wsl:") {
		return ""
	}
	distro := strings.TrimPrefix(execution, "wsl:")
	probeCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	cmd := exec.CommandContext(probeCtx, "wsl.exe", "-d", distro, "--", "ip", "route", "show", "default")
	cmd.Env = append(os.Environ(), "WSL_UTF8=1")
	output, err := cmd.Output()
	if err != nil {
		return ""
	}
	fields := strings.Fields(strings.ReplaceAll(string(output), "\x00", ""))
	for i := 0; i+1 < len(fields); i++ {
		if fields[i] == "via" {
			candidate := strings.TrimSpace(fields[i+1])
			if candidate != "" && !strings.ContainsAny(candidate, "\r\n") {
				return candidate
			}
		}
	}
	return ""
}

func isLoopbackHost(host string) bool {
	switch strings.ToLower(strings.TrimSpace(host)) {
	case "127.0.0.1", "::1", "localhost":
		return true
	default:
		return false
	}
}

func parseEnvFile(data string) ([]envVar, error) {
	data = strings.TrimPrefix(data, string(rune(0xFEFF)))
	result := make([]envVar, 0, 16)
	for number, raw := range strings.Split(data, "\n") {
		line := strings.TrimSpace(strings.TrimSuffix(raw, "\r"))
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		if !ok {
			return nil, fmt.Errorf("第 %d 行缺少 '='", number+1)
		}
		key = strings.TrimSpace(key)
		if !validEnvKey(key) {
			return nil, fmt.Errorf("第 %d 行变量名无效", number+1)
		}
		value = strings.TrimSpace(value)
		if len(value) >= 2 && value[0] == '"' && value[len(value)-1] == '"' {
			unquoted, err := strconv.Unquote(value)
			if err != nil {
				return nil, fmt.Errorf("第 %d 行无法解析引号值: %w", number+1, err)
			}
			value = unquoted
		}
		if strings.ContainsAny(value, "\x00\r\n") {
			return nil, fmt.Errorf("第 %d 行变量值包含非法控制字符", number+1)
		}
		result = append(result, envVar{Key: key, Value: value})
	}
	return result, nil
}

func validEnvKey(key string) bool {
	if key == "" {
		return false
	}
	for i, r := range key {
		if r == '_' || (r >= 'A' && r <= 'Z') || (r >= 'a' && r <= 'z') {
			continue
		}
		if i > 0 && r >= '0' && r <= '9' {
			continue
		}
		return false
	}
	return true
}

// mergeEnvironment returns base with extra values applied. On Windows keys are
// compared case-insensitively, matching the operating system.
func mergeEnvironment(base []string, extra []envVar) []string {
	keyOf := func(key string) string {
		if goruntime.GOOS == "windows" {
			return strings.ToUpper(key)
		}
		return key
	}
	index := make(map[string]int, len(base)+len(extra))
	result := make([]string, 0, len(base)+len(extra))
	for _, item := range base {
		key, _, ok := strings.Cut(item, "=")
		if !ok || key == "" {
			continue
		}
		normalized := keyOf(key)
		if _, exists := index[normalized]; exists {
			continue
		}
		index[normalized] = len(result)
		result = append(result, item)
	}
	for _, item := range extra {
		normalized := keyOf(item.Key)
		line := item.Key + "=" + item.Value
		if position, exists := index[normalized]; exists {
			result[position] = line
			continue
		}
		index[normalized] = len(result)
		result = append(result, line)
	}
	return result
}

// redactedEnvValues returns the credential values used for log redaction.
func envSecretValues(values []envVar) []string {
	var result []string
	for _, item := range values {
		if strings.Contains(item.Key, "PASSWORD") && item.Value != "" {
			result = append(result, item.Value)
			logging.RegisterSecret(item.Value)
		}
	}
	return result
}

// ensureEnvFile regenerates the environment file for a workspace.
func (m *Manager) ensureEnvFile(ctx context.Context, ws *workspace.Workspace) ([]envVar, error) {
	values, err := m.WriteEnvFile(ctx, ws)
	if err != nil {
		return nil, err
	}
	envSecretValues(values)
	return values, nil
}
